#!/usr/bin/env node
// Generates src/lib/traditional.data.generated.ts from vendored OpenCC dictionaries
// (scripts/opencc/*.txt). Run manually with `npm run gen:traditional` whenever the
// vendored dictionaries change. Output is committed to git — this is not part of
// the build.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const OPENCC_DIR = path.join(__dirname, 'opencc')
const OUTPUT_FILE = path.join(__dirname, '..', 'src', 'lib', 'traditional.data.generated.ts')

/** Parses an OpenCC dictionary file into a Map<key, firstCandidate>. */
function parseDictionary(filename) {
  const raw = readFileSync(path.join(OPENCC_DIR, filename), 'utf8')
  const map = new Map()
  for (const line of raw.split('\n')) {
    if (!line || line.startsWith('#')) continue
    const tabIndex = line.indexOf('\t')
    if (tabIndex === -1) continue
    const key = line.slice(0, tabIndex)
    const candidates = line.slice(tabIndex + 1).trim().split(' ')
    if (!key || candidates.length === 0 || !candidates[0]) continue
    map.set(key, candidates[0])
  }
  return map
}

const stCharacters = parseDictionary('STCharacters.txt')
const stPhrases = parseDictionary('STPhrases.txt')
const twVariants = parseDictionary('TWVariants.txt')

/** Applies TWVariants char-by-char to a (possibly multi-char) string. */
function applyTwVariants(text) {
  let out = ''
  for (const ch of text) {
    out += twVariants.get(ch) ?? ch
  }
  return out
}

// Character table: candidate1 of STCharacters, with TWVariants applied, kept
// only when the result actually differs from the simplified key. CHAR_KEYS/
// CHAR_VALUES are encoded as parallel flat strings indexed by position, so
// both the key and the result must be exactly one UTF-16 code unit — this
// drops ~1169 rare astral-plane (surrogate-pair) characters. Verified: the
// intersection of dropped keys with every character across src/data/lessons/
// *.txt (515 distinct chars) is empty, so this is a no-op for this app's
// vocabulary today. If the corpus ever grows to include one of the dropped
// keys, switch CHAR_KEYS/CHAR_VALUES to the same "key\tvalue\n" line encoding
// used for PHRASE_DATA instead of positional strings.
const charMap = new Map()
for (const [key, candidate1] of stCharacters) {
  if (key.length !== 1) continue
  const result = applyTwVariants(candidate1)
  if (result.length !== 1) continue
  if (result !== key) charMap.set(key, result)
}

function mapByChar(text) {
  let out = ''
  for (const ch of text) {
    out += charMap.get(ch) ?? ch
  }
  return out
}

// Phrase override table: STPhrases candidate1 (with TWVariants applied) kept
// only when it differs from the char-by-char mapping of the same key, and only
// for keys of length <= 3 (verified to match the full table on this app's
// corpus — see traditional.test.ts).
const phraseOverrides = new Map()
for (const [key, candidate1] of stPhrases) {
  if (key.length > 3) continue
  const phraseResult = applyTwVariants(candidate1)
  const charResult = mapByChar(key)
  if (phraseResult !== charResult) phraseOverrides.set(key, phraseResult)
}

const charKeys = [...charMap.keys()].join('')
const charValues = [...charMap.values()].join('')

const phraseLines = [...phraseOverrides.entries()].map(([key, value]) => `${key}\t${value}`)
const phraseData = phraseLines.join('\n')

const banner = `// Generated by scripts/gen-traditional.mjs from scripts/opencc/*.txt.
// Do not edit by hand — edit src/lib/traditional.overrides.ts instead, or
// update the vendored dictionaries and re-run \`npm run gen:traditional\`.
`

const output = `${banner}
/** Simplified chars concatenated; CHAR_VALUES[i] is the traditional form of CHAR_KEYS[i]. */
export const CHAR_KEYS = ${JSON.stringify(charKeys)}
export const CHAR_VALUES = ${JSON.stringify(charValues)}

/** "simplified\\ttraditional" lines, newline-separated. Phrase-level overrides (length <= 3). */
export const PHRASE_DATA = ${JSON.stringify(phraseData)}
`

writeFileSync(OUTPUT_FILE, output, 'utf8')

console.log(`Char table: ${charMap.size} entries`)
console.log(`Phrase override table: ${phraseOverrides.size} entries`)
console.log(`Wrote ${OUTPUT_FILE}`)
